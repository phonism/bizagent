// Generate docs/tools.md from the registered Agent tools, or check that it is current.
// Usage: node scripts/tools-reference.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises'
import { registerTools } from '../lib/tools.js'

const target = new URL('../docs/tools.md', import.meta.url)
const definitions = []
registerTools({ tools: { register(definition) { definitions.push(definition) } } }, null, null, null)

const GROUPS = [
  ['Home and memory', ['bizagent_home_status', 'bizagent_memory_']],
  ['Other Homes (read-only Frames)', ['bizagent_agent_search', 'bizagent_frame_']],
  ['Proposals and shared Knowledge', ['bizagent_proposals', 'bizagent_knowledge_']],
  ['Session evidence and Worklogs', ['bizagent_episode', 'bizagent_evidence_read', 'bizagent_worklog']],
  ['Learning reviews', ['bizagent_learning_']],
  ['Inbox', ['bizagent_inbox']],
  ['Formal Work', ['bizagent_work']],
  ['Projects', ['bizagent_project']],
]

function groupOf(name) {
  // A longer matching prefix wins, so bizagent_memory_propose stays with memory.
  let best
  for (const [title, prefixes] of GROUPS) {
    for (const prefix of prefixes) {
      if (name === prefix || name.startsWith(prefix)) {
        if (best === undefined || prefix.length > best.length) best = { title, length: prefix.length }
      }
    }
  }
  if (best === undefined) throw new Error(`no documentation group for ${name}`)
  return best.title
}

function typeOf(schema) {
  if (schema.enum) return schema.enum.map(value => `\`${value}\``).join(', ')
  if (schema.type === 'array') return `${schema.items ? typeOf(schema.items) : 'value'}[]`
  return schema.type ?? 'value'
}

function cell(text) {
  return String(text ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ')
}

function render() {
  const lines = [
    '# Agent tools',
    '',
    '<!-- Generated by scripts/tools-reference.mjs from the registered tools. Do not edit by hand. -->',
    '',
    `BizAgent registers ${definitions.length} tools in every DSH Session it binds to a Home.`,
    'Each tool acts as the Session\'s own Home; writes to another Home go through proposals,',
    'Inbox messages, formal Work, or Projects. Results are compact JSON.',
    '',
  ]
  for (const [title] of GROUPS) {
    const members = definitions.filter(definition => groupOf(definition.name) === title)
    if (members.length === 0) continue
    lines.push(`## ${title}`, '')
    for (const definition of members) {
      lines.push(`### \`${definition.name}\``, '', cell(definition.description), '')
      const properties = Object.entries(definition.parameters?.properties ?? {})
      if (properties.length === 0) {
        lines.push('No parameters.', '')
        continue
      }
      const required = new Set(definition.parameters?.required ?? [])
      lines.push('| Parameter | Type | Required | Description |', '| --- | --- | --- | --- |')
      for (const [name, schema] of properties) {
        lines.push(`| \`${name}\` | ${cell(typeOf(schema))} | ${required.has(name) ? 'yes' : ''} | ${cell(schema.description)} |`)
      }
      lines.push('')
    }
  }
  return `${lines.join('\n').trimEnd()}\n`
}

const content = render()
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== content) {
    process.stderr.write('docs/tools.md is out of date; run node scripts/tools-reference.mjs\n')
    process.exitCode = 1
  }
} else {
  await writeFile(target, content)
  process.stdout.write(`Wrote docs/tools.md (${definitions.length} tools).\n`)
}
